use crate::{Error, Result, digest, json, read, safe_path};
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

pub type Files = BTreeMap<String, String>;
pub const INVENTORY: &str = ".harness-generated.json";
const TREES: [&str; 4] = [
    ".codex/agents",
    ".claude/agents",
    ".agents/skills",
    ".claude/skills",
];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Manifest {
    version: u32,
    agents: Vec<Agent>,
    skills: Vec<String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Agent {
    name: String,
    description: String,
    writable: bool,
    codex_model: String,
    codex_effort: String,
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Inventory {
    pub version: u32,
    pub files: BTreeMap<String, String>,
}

fn identifier(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 80
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

fn quote(text: &str) -> Result<String> {
    serde_json::to_string(text).map_err(|_| Error::Invalid("invalid text"))
}

pub fn owned(path: &str) -> bool {
    matches!(
        path,
        "AGENTS.md"
            | "CLAUDE.md"
            | ".codex/config.toml"
            | ".codex/hooks.json"
            | ".claude/settings.json"
            | INVENTORY
    ) || TREES
        .iter()
        .any(|tree| path.starts_with(&format!("{tree}/")))
}

pub fn render(root: &Path) -> Result<Files> {
    let code_hash = crate::verify_build(root)?;
    let manifest: Manifest = serde_json::from_str(&read(root, "harness/manifest.json")?)
        .map_err(|_| Error::Invalid("manifest schema"))?;
    if manifest.version != 1 || manifest.agents.len() != 5 || manifest.skills.len() != 6 {
        return Err(Error::Invalid(
            "expected version 1, five agents and six skills",
        ));
    }
    let mut files = Files::new();
    let instructions = format!(
        "<!-- Generated from harness/instructions.md; do not edit. -->\n{}",
        read(root, "harness/instructions.md")?
    );
    files.insert("AGENTS.md".into(), instructions.clone());
    files.insert("CLAUDE.md".into(), instructions);
    files.insert(".codex/config.toml".into(),
        "# Generated by xtask. Host permissions and trust remain authoritative.\n[agents]\nenabled = true\nmax_concurrent_threads_per_session = 3\n".into());
    let mut names = BTreeSet::new();
    for agent in manifest.agents {
        if !identifier(&agent.name)
            || !names.insert(agent.name.clone())
            || agent.codex_model != "gpt-6-astra"
            || !matches!(agent.codex_effort.as_str(), "medium" | "high")
        {
            return Err(Error::Invalid("agent name or platform model/effort"));
        }
        let body = read(root, &format!("harness/agents/{}.md", agent.name))?;
        let boundary = if agent.writable {
            "Tools: scoped file reading, search, patching, and local Rust checks. Sandbox: workspace-write, bounded by host policy. Require explicit file ownership from the parent before editing. You are not alone: preserve concurrent work."
        } else {
            "Tools: read and search only. Sandbox: read-only. Do not execute a shell, edit, install, run network requests, or delegate. Ask the parent to run any required verification."
        };
        let prompt = format!(
            "{body}\n{boundary}\nNever widen permissions or scope. Stop and report missing authority, secrets, unsafe paths, or conflicting ownership. No global writes, product execution, commits or remote writes.\n"
        );
        files.insert(format!(".codex/agents/{}.toml", agent.name), format!(
            "# Generated from harness/agents/{}.md\nname = {}\ndescription = {}\nmodel = {}\nmodel_reasoning_effort = {}\nsandbox_mode = {}\ndeveloper_instructions = {}\n",
            agent.name, quote(&agent.name)?, quote(&agent.description)?, quote(&agent.codex_model)?,
            quote(&agent.codex_effort)?, quote(if agent.writable { "workspace-write" } else { "read-only" })?, quote(&prompt)?));
        let tools = if agent.writable {
            "Read, Glob, Grep, Bash, Edit, Write"
        } else {
            "Read, Glob, Grep"
        };
        files.insert(format!(".claude/agents/{}.md", agent.name), format!(
            "---\nname: {}\ndescription: {}\ntools: {tools}\nmodel: inherit\npermissionMode: default\n---\n<!-- Generated; edit harness/agents/{}.md. -->\n{}\nClaude sandbox: inherit host restrictions; tool lists are not OS isolation. Model and effort inherit the session.\n",
            agent.name, quote(&agent.description)?, agent.name, prompt));
    }
    names.clear();
    for skill in manifest.skills {
        if !identifier(&skill) || !names.insert(skill.clone()) {
            return Err(Error::Invalid("skill name"));
        }
        let content = read(root, &format!("harness/skills/{skill}/SKILL.md"))?;
        if !content.starts_with(&format!("---\nname: {skill}\ndescription: ")) {
            return Err(Error::Invalid("skill frontmatter"));
        }
        for heading in [
            "## Triggers",
            "## Non-triggers",
            "## Inputs",
            "## Steps",
            "## Checks",
            "## Stop",
        ] {
            if !content.contains(heading) {
                return Err(Error::Invalid("skill contract incomplete"));
            }
        }
        let scenarios = read(
            root,
            &format!("harness/skills/{skill}/evals/scenarios.json"),
        )?;
        validate_scenarios(&scenarios)?;
        for tree in [".agents/skills", ".claude/skills"] {
            files.insert(format!("{tree}/{skill}/SKILL.md"), content.clone());
            files.insert(
                format!("{tree}/{skill}/evals/scenarios.json"),
                scenarios.clone(),
            );
        }
    }
    let wrapper = read(root, "harness/session-start.sh")?;
    for host in ["codex", "claude"] {
        // Use tracked root lookup rather than interpolating a machine-local path.
        let command =
            format!("sh \"$(git rev-parse --show-toplevel)/harness/session-start.sh\" {host}");
        let config = json!({"hooks":{"SessionStart":[{"matcher":"startup|resume|clear|compact","hooks":[{
            "type":"command", "command":command, "timeout":10
        }]}]}});
        files.insert(
            if host == "codex" {
                ".codex/hooks.json"
            } else {
                ".claude/settings.json"
            }
            .into(),
            json(&config)?,
        );
    }
    // Include launcher integrity in native definitions so a source change changes
    // the hook definition hash reviewed by the user. No trust is written here.
    for path in [".codex/hooks.json", ".claude/settings.json"] {
        let mut value: serde_json::Value =
            serde_json::from_str(&files[path]).map_err(|_| Error::Invalid("hook serialization"))?;
        let command = value["hooks"]["SessionStart"][0]["hooks"][0]["command"]
            .as_str()
            .ok_or(Error::Invalid("hook command"))?;
        value["hooks"]["SessionStart"][0]["hooks"][0]["command"] = format!(
            "{command} # launcher-sha256:{} rust-sha256:{code_hash}",
            digest(wrapper.as_bytes())
        )
        .into();
        files.insert(path.into(), json(&value)?);
    }
    let inventory = Inventory {
        version: 1,
        files: files
            .iter()
            .map(|(p, v)| (p.clone(), digest(v.as_bytes())))
            .collect(),
    };
    files.insert(INVENTORY.into(), json(&inventory)?);
    Ok(files)
}

fn validate_scenarios(text: &str) -> Result<()> {
    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct Scenarios {
        positive: Vec<String>,
        negative: Vec<String>,
    }
    let scenarios: Scenarios =
        serde_json::from_str(text).map_err(|_| Error::Invalid("skill scenarios"))?;
    if scenarios.positive.len() < 8
        || scenarios.negative.len() < 2
        || scenarios
            .positive
            .iter()
            .chain(&scenarios.negative)
            .any(|s| s.trim().is_empty())
    {
        return Err(Error::Invalid(
            "skill scenarios require eight positives and two negatives",
        ));
    }
    Ok(())
}

pub fn inventory(root: &Path) -> Result<Inventory> {
    let inventory: Inventory = serde_json::from_str(&read(root, INVENTORY)?)
        .map_err(|_| Error::Invalid("generated inventory schema"))?;
    if inventory.version != 1 || inventory.files.len() > 100 {
        return Err(Error::Invalid("generated inventory version or size"));
    }
    for (path, hash) in &inventory.files {
        if !owned(path)
            || path == INVENTORY
            || hash.len() != 64
            || !hash.bytes().all(|b| b.is_ascii_hexdigit())
        {
            return Err(Error::Invalid("inventory ownership or hash"));
        }
        safe_path(root, path)?;
    }
    Ok(inventory)
}

pub fn reject_stale(root: &Path, expected: &BTreeSet<String>) -> Result<()> {
    fn visit(root: &Path, relative: &str, expected: &BTreeSet<String>) -> Result<()> {
        let path = safe_path(root, relative)?;
        if !path.exists() {
            return Ok(());
        }
        for item in fs::read_dir(path).map_err(|e| Error::Io("list projections", e))? {
            let item = item.map_err(|e| Error::Io("list projection entry", e))?;
            let name = item
                .file_name()
                .into_string()
                .map_err(|_| Error::Invalid("non UTF-8 path"))?;
            let relative = format!("{relative}/{name}");
            let path = safe_path(root, &relative)?;
            if path.is_dir() {
                visit(root, &relative, expected)?;
            } else if !expected.contains(&relative) {
                return Err(Error::Drift(relative));
            }
        }
        Ok(())
    }
    for tree in TREES {
        visit(root, tree, expected)?;
    }
    Ok(())
}

pub fn check(root: &Path) -> Result<()> {
    let expected = render(root)?;
    reject_stale(root, &expected.keys().cloned().collect())?;
    for (path, content) in expected {
        if read(root, &path)? != content {
            return Err(Error::Drift(path));
        }
    }
    Ok(())
}
